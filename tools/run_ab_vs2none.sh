#!/bin/bash
# 决定性问题：**一台价值网络 Bot 对两台完全相同的纯搜索 Bot**（2026-10-02）。
#
# 【为什么这个场次最干净】
#   前面的组都是"三个不同配置各占一席"，谁强谁弱被三家互吃搅在一起。
#   这里让 **n1 与 n2 用同一个配置**（进程内还共用同一个"关闭"顾问对象），
#   所以它们强度**严格相等** ⇒ 它们之间的任何差异就是噪声地板；
#   而 `v` 面对的是两台等价对手，赢率是否显著高于 1/3 就是**"是否更强"的直接证据**。
#
# 【已知的场次依赖（必须带进判读）】
#   {n, v, bal }（第三个是弱手）⇒ v **32~37%**，p≤0.007
#   {n, v, v   }（第三个是价值网络）⇒ 判和率 31%→54%，三方全平
#   ⇒ 也就是说：**"第三家是谁"能翻转结论**。本组把第三家换成"与第一家相同的纯搜索"，
#     是"两台纯搜索 + 一台价值网络"这个**对弈台最常见的形态**。
#
# 【判读】
#   v 的胜率 ≈ 33% 且 v vs n1、v vs n2 都不显著 ⇒ 与纯搜索**同级**，别上线
#   v 的胜率 > 33% 且 v vs n1、v vs n2 都显著（p<0.05）⇒ **确实更强**，可上线
#   特别注意 n1 vs n2 这一对照：**它必须不显著**，否则说明噪声地板太大，本组也读不出来
cd /root/autodl-tmp/sanchi || exit 1
PY=/root/miniconda3/bin/python
BASE="--workers 8 --tl 5.0 --depth 1 --maxply 300 --threads 1 --seed0 2200000"

run() {   # $1 = 第二个 v 的 cfg（不同 λ 或不同权重）  $2 = 输出名  $3 说明
    echo "=== [$(date '+%F %T')] $3 ==="
    $PY -u tools/ab_match.py $BASE --games 300 \
        --cfg n1=- --cfg n2=- --cfg "$1" \
        --out "_对照实验/$2"
}

run "v=value_mlp_1233.json:0.35" ab_V1_vs_2none.json "V1: 一台 v1233@0.35 对两台纯搜索"
run "v=value_mlp_1233.json:0.15" ab_V2_vs_2none_l15.json "V2: 改用 λ=0.15（治'太和平'）对两台纯搜索"
echo "=== [$(date '+%F %T')] VS2NONE DONE ==="
